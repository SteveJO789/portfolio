let language = "en";
function setLanguage(value) {
  language = Object.hasOwn(dictionary, value) ? value : "en";
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[language][element.dataset.i18n];
    if (typeof value === "string") element.textContent = value;
  });
  languageButtons.forEach((button) =>
    button.setAttribute(
      "aria-pressed",
      String(button.dataset.lang === language),
    ),
  );
  document.title =
    language === "th"
      ? "Pipat Sassana | พัฒนาระบบ AI, IoT และ Automation"
      : "Pipat Sassana | AI, IoT & Automation Engineer";
  try {
    localStorage.setItem("portfolio-lang", language);
  } catch {
    /* Language switching remains available without storage. */
  }
}
let savedLanguage;
